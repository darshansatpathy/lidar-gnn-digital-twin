"""The evaluation report: segmentation against the baseline under four conditions, and the twin."""

from __future__ import annotations

import time
from dataclasses import dataclass
from typing import Any

import numpy as np

from lidartwin import data, features, metrics, scenes, train, twin
from lidartwin.model import DGCNN, parameters
from lidartwin.scenes import CLASSES


@dataclass
class Results:
    segmentation: dict[str, dict[str, dict[str, float]]]  # condition -> model -> metrics
    twin_scores: list[twin.KindScore]
    changes: tuple[int, int, int]
    oracle_changes: tuple[int, int, int]
    pairs: int
    seconds_per_scene: float
    points_per_scene: float
    info: dict[str, Any]


def run(model: DGCNN, baseline: Any, test_seeds: list[int], pair_seeds: list[int], info: dict[str, Any]) -> Results:
    seg: dict[str, dict[str, dict[str, float]]] = {}
    seconds = points = 0.0
    test_prepared: list[data.Prepared] = []
    test_labels: list[np.ndarray] = []
    for name, kwargs in data.CONDITIONS.items():
        prepared = data.prepare_all(test_seeds, **kwargs)
        start = time.time()
        if name == "test":
            # Two passes voting on the held-out streets; these predictions also build the twin below.
            test_prepared = prepared
            test_labels = [train.predict(model, p, passes=2, seed=i) for i, p in enumerate(prepared)]
            gnn = metrics.summary(np.asarray(sum(metrics.confusion(p.scene.labels, y) for p, y in zip(prepared, test_labels, strict=True))))
        else:
            gnn = train.evaluate(model, prepared, passes=1)
        elapsed = (time.time() - start) / len(prepared)
        seg[name] = {"DGCNN": gnn, "gradient boosting": train.evaluate_baseline(baseline, prepared)}
        if name == "test":
            seconds, points = elapsed, float(np.mean([len(p.scene) for p in prepared]))
    # The twin, from the model's predictions on the test streets.
    scores: dict[str, list[twin.KindScore]] = {}
    for p, labels in zip(test_prepared, test_labels, strict=True):
        for s in twin.score(twin.extract(p.scene, labels, p.hag), p.scene):
            scores.setdefault(s.kind, []).append(s)
    merged = [
        twin.KindScore(
            k,
            sum(s.registry for s in v),
            sum(s.detected for s in v),
            sum(s.matched for s in v),
            float(np.nanmean([s.position_error_m for s in v])),
            float(np.nanmedian([s.height_error_m for s in v])),
        )
        for k, v in scores.items()
    ]
    found, oracle = np.zeros(3, int), np.zeros(3, int)
    for seed in pair_seeds:
        before, after = scenes.make_pair(seed)
        pb, pa = data.prepare(before), data.prepare(after)
        truth = twin.true_changes(before, after)
        d = twin.diff(twin.extract(before, train.predict(model, pb, 1), pb.hag), twin.extract(after, train.predict(model, pa, 1), pa.hag))
        found += twin.change_score(d, truth)
        o = twin.diff(twin.extract(before, before.labels, pb.hag), twin.extract(after, after.labels, pa.hag))
        oracle += twin.change_score(o, truth)
    return Results(
        seg,
        merged,
        (int(found[0]), int(found[1]), int(found[2])),
        (int(oracle[0]), int(oracle[1]), int(oracle[2])),
        len(pair_seeds),
        seconds,
        points,
        info,
    )


def markdown(r: Results) -> str:
    t = r.segmentation["test"]
    g, b = t["DGCNN"], t["gradient boosting"]
    lines = [
        "# Evaluation report",
        "",
        f"**DGCNN mIoU {g['miou']:.3f} against {b['miou']:.3f} for gradient boosting on handcrafted features**, on {r.info['test_scenes']} "
        f"held-out streets ({r.points_per_scene:,.0f} points each on average). Generated by `ltw evaluate`.",
        "",
        "## Segmentation (intersection over union)",
        "",
        "| Condition | Model | mIoU | Accuracy | " + " | ".join(CLASSES) + " |",
        "|---|---|---|---|" + "---|" * len(CLASSES),
    ]
    for cond, models in r.segmentation.items():
        for name, m in models.items():
            cells = " | ".join(f"{m[f'iou_{c}']:.3f}" for c in CLASSES)
            lines.append(f"| {cond} | {name} | **{m['miou']:.3f}** | {m['accuracy']:.3f} | {cells} |")
    lines += [
        "",
        "The conditions are scans the model never trained on: the held-out streets as generated, the same streets with half the "
        "points, with 5 cm instead of 1.5 cm range noise, and with buildings taller than any in training (14 to 30 m, against 6 to 18 m).",
        "",
        f"Inference: {r.seconds_per_scene:.1f} s per street on 2 CPU cores, two passes voting (one pass under the other conditions and for the change pairs).",
        "",
        "## Twin: assets against the registry",
        "",
        "| Asset | In registry | Detected | Matched | Precision | Recall | Mean position error | Median height error |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in r.twin_scores:
        lines.append(
            f"| {s.kind} | {s.registry} | {s.detected} | {s.matched} | {s.precision:.3f} | {s.recall:.3f} | {s.position_error_m:.2f} m | {s.height_error_m:.2f} m |"
        )
    tp, fp, fn = r.changes
    otp, ofp, ofn = r.oracle_changes
    lines += [
        "",
        "Building heights are the highest point the scanner sees on the facade; for tall buildings close to the street that is "
        "below the roof line, so the height error there is a property of the scan, not the model.",
        "",
        "## Twin: change detection between two scans",
        "",
        f"{r.pairs} streets scanned twice. Between scans one pole is removed, one tree planted and one building gains a storey "
        f"(+3.2 m); every parked vehicle moves, and must not be reported.",
        "",
        "| Labels | Changes found | False alarms | Missed |",
        "|---|---|---|---|",
        f"| DGCNN predictions | {tp} of {tp + fn} | {fp} | {fn} |",
        f"| Ground truth (upper bound) | {otp} of {otp + ofn} | {ofp} | {ofn} |",
        "",
        "## Model",
        "",
        f"DGCNN, {r.info['parameters']:,} parameters: three EdgeConv layers (k = 16; the first on coordinates, the next two on "
        f"learned features), global context, per-point classifier. Trained for {r.info['epochs']} epochs on "
        f"{r.info['train_scenes']} streets, best epoch chosen on {r.info['val_scenes']} validation streets. Inputs per point: "
        "position in its 20 m block, height above a terrain model, intensity.",
    ]
    return "\n".join(lines) + "\n"


def info(model: DGCNN, manifest: dict[str, Any]) -> dict[str, Any]:
    return {
        "parameters": parameters(model),
        "epochs": manifest.get("epochs"),
        "train_scenes": len(scenes.SPLITS["train"]),
        "val_scenes": manifest.get("val_scenes", 8),
        "test_scenes": len(scenes.SPLITS["test"]),
    }


__all__ = ["Results", "features", "info", "markdown", "run"]
